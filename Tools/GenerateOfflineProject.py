#!/usr/bin/env python3
"""Explicit network-blocked QA variant; never substitute this for Firebase release QA."""
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parents[1]
source = (root / 'project.yml').read_text()
source, package_count = re.subn(r'^  Firebase:\n(?:    .*\n)+', '', source, flags=re.MULTILINE)
source, product_count = re.subn(r'      - package: Firebase\n        product: \w+\n', '', source)
if package_count != 1 or product_count != 2:
    raise SystemExit('Firebase dependency layout changed; update offline derivation explicitly')
source = source.replace('name: SortScape\n', 'name: SortScapeOffline\n', 1)
(root / 'project-offline.yml').write_text('# Generated by Tools/GenerateOfflineProject.py. No Firebase; reporting unavailable.\n' + source)
subprocess.run(['xcodegen', 'generate', '--spec', 'project-offline.yml'], cwd=root, check=True)
